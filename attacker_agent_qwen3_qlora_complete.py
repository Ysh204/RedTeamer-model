"""## 9. Inference function"""

@torch.no_grad()
def analyze_source(source_code,filename="snippet.py",context=""):
    model.eval()
    model.config.use_cache=True
    prompt=tok.apply_chat_template(
        [{"role":"system","content":ATTACKER_SYSTEM},
         {"role":"user","content":build_user(source_code,filename,context)}],
        tokenize=False,add_generation_prompt=True,enable_thinking=False
    )
    enc=tok(prompt,return_tensors="pt",add_special_tokens=False).to(model.device)
    out=model.generate(enc["input_ids"],attention_mask=enc["attention_mask"],
                       max_new_tokens=MAX_NEW_TOKENS,do_sample=False,
                       pad_token_id=tok.pad_token_id,eos_token_id=tok.eos_token_id)
    raw=tok.decode(out[0][enc["input_ids"].shape[1]:],skip_special_tokens=True)
    obj=extract_json(raw)
    if obj is None: return {"valid":False,"error":"Unparseable JSON","raw":raw}
    valid,reason=validate_report(obj,source_code)
    return {"valid":valid,"validation":reason,"report":obj,"raw":raw}

